async function currentFields(databasePath: string, itemId: string) {
  const db = openDatabase(databasePath);
  try { return (await projected(db)).filter((field) => field.target.kind === "item" && field.target.itemId === itemId); }
  finally { db.close(); }
}
function title(databasePath: string, sourceId: string, itemId: string, versionId: string, author: "ai" | "user", text: string, key: string, expectedTitleRevisionId: string | null) {
  const db = openDatabase(databasePath);
  try { return db.transaction(() => writeTitle(db, { sourceId, target: { kind: "item", itemId, versionId }, author, text, key, payloadHash: key, expectedTitleRevisionId })).immediate(); }
  finally { db.close(); }
}

